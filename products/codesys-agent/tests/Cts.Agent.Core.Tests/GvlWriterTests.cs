using System;
using System.Collections.Generic;
using System.IO;
using Xunit;
using Cts.Visu;

namespace Cts.Agent.Tests
{
    public class GvlWriterTests : IDisposable
    {
        readonly string root = Path.Combine(Path.GetTempPath(), "cts-gvl-" + Guid.NewGuid().ToString("N"));

        public GvlWriterTests()
        {
            Directory.CreateDirectory(root);
        }

        public void Dispose()
        {
            Directory.Delete(root, true);
        }

        static Sketch.Element TextElement(string variable, string format)
        {
            var element = new Sketch.Element { Type = "textfield" };
            element.SpecParams["text_var"] = variable;
            element.SpecParams["text"] = format;
            return element;
        }

        [Fact]
        public void Creates_explicit_gvl_with_inferred_types_and_is_idempotent()
        {
            var target = Path.Combine(root, "custom", "Visual.st");
            var elements = new List<Sketch.Element> {
                TextElement("PLC.speed", "%3.1f"),
                TextElement("PLC.count", "%d"),
            };
            var first = GvlWriter.Ensure(root, elements, "VisuVars", target);
            Assert.True(first.Written);
            Assert.Equal(Path.GetFullPath(target), first.Path);
            var content = File.ReadAllText(target);
            Assert.Contains("speed : REAL", content);
            Assert.Contains("count : INT", content);

            var second = GvlWriter.Ensure(root, elements, "VisuVars", target);
            Assert.False(second.Written);
            Assert.Equal(content, File.ReadAllText(target));
        }

        [Fact]
        public void The_named_gvl_is_found_in_an_application_folder()
        {
            var target = Path.Combine(root, "PLC", "Plc Logic", "Application", "hmi", "VisuVars.st");
            Directory.CreateDirectory(Path.GetDirectoryName(target));
            File.WriteAllText(target, "VAR_GLOBAL\n    run : BOOL;\nEND_VAR\n");
            var result = GvlWriter.Ensure(root, new List<Sketch.Element> { TextElement("VisuVars.run", "%d"), TextElement("VisuVars.n", "%d") }, "VisuVars", null);
            Assert.Equal(target, result.Path);
            Assert.Equal("VAR_GLOBAL\n    run : BOOL;\n\n    {attribute 'hide'}\n    // Auto-generated by cts visu from-svg --gvl\n    n : INT;\nEND_VAR\n",
                File.ReadAllText(target));
            Assert.False(Directory.Exists(Path.Combine(root, "POUs")));
        }

        [Fact]
        public void Two_gvls_of_the_name_write_nothing_and_ask_for_the_file()
        {
            foreach (var app in new[] { "A", "B" })
            {
                var file = Path.Combine(root, app, "VisuVars.st");
                Directory.CreateDirectory(Path.GetDirectoryName(file));
                File.WriteAllText(file, "VAR_GLOBAL\nEND_VAR\n");
            }
            var result = GvlWriter.Ensure(root, new List<Sketch.Element> { TextElement("VisuVars.n", "%d") }, "VisuVars", null);
            Assert.Null(result.Path);
            Assert.Contains(result.Warnings, warning => warning.Contains("--gvl-file"));
            Assert.Equal("VAR_GLOBAL\nEND_VAR\n", File.ReadAllText(Path.Combine(root, "A", "VisuVars.st")));
        }

        [Fact]
        public void Declarations_are_aligned_and_kept_apart_from_an_existing_table()
        {
            var target = Path.Combine(root, "POUs", "VisuVars.st");
            Directory.CreateDirectory(Path.GetDirectoryName(target));
            File.WriteAllText(target, "VAR_GLOBAL\n    run      : BOOL;\n    setpoint : REAL;\nEND_VAR\n");
            GvlWriter.Ensure(root, new List<Sketch.Element> { TextElement("VisuVars.speed", "%3.1f"), TextElement("VisuVars.n", "%d") }, "VisuVars", null);
            Assert.Equal("VAR_GLOBAL\n    run      : BOOL;\n    setpoint : REAL;\n\n    {attribute 'hide'}\n    // Auto-generated by cts visu from-svg --gvl\n"
                + "    n     : INT;\n    speed : REAL;\nEND_VAR\n", File.ReadAllText(target));
        }

        [Fact]
        public void Known_project_gvl_reports_missing_members_without_creating_duplicate_declarations()
        {
            var existing = Path.Combine(root, "POUs", "PLC.st");
            Directory.CreateDirectory(Path.GetDirectoryName(existing));
            File.WriteAllText(existing, "VAR_GLOBAL\n    speed : REAL;\nEND_VAR\n");
            var result = GvlWriter.Ensure(root, new List<Sketch.Element> {
                TextElement("PLC.speed", "%f"),
                TextElement("PLC.missing", "%d"),
            }, "VisuVars", null);
            Assert.False(result.Written);
            Assert.Single(result.Warnings);
            Assert.False(File.Exists(Path.Combine(root, "POUs", "VisuVars.st")));
        }
    }
}
